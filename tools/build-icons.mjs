#!/usr/bin/env node
// Writes src/ui/icon-paths.js: the SVG path of every game-icons.net icon that src/ui/icon-map.js names
// (DESIGN 9, "Icons"). Only the icons in use are kept, and their coordinates are rounded to whole units of
// the 512-unit box (a fifth of a pixel at the largest size the HUD draws them), which halves the file.
//
//   npm pack @iconify-json/game-icons && tar xzf iconify-json-game-icons-*.tgz
//   node tools/build-icons.mjs package/icons.json
//
// The icons are CC BY 3.0 by the game-icons.net authors (vendor/game-icons/LICENSE.md).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ICON_MAP } from '../src/ui/icon-map.js';

const ARGS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, a: 7, z: 0 };

/**
 * Rewrite a path with whole-unit coordinates. Relative commands stay relative (shorter), but each offset is
 * taken from the rounded point already written, so rounding never piles up along a long outline.
 */
export function roundPath(d) {
  let i = 0;
  let cmd = '';
  let x = 0; let y = 0; // exact current point
  let rx = 0; let ry = 0; // rounded current point (what the output has reached)
  let sx = 0; let sy = 0; let rsx = 0; let rsy = 0; // subpath start
  const out = [];
  const R = Math.round;
  const skip = () => { while (i < d.length && /[\s,]/.test(d[i])) i++; };
  const num = () => {
    skip();
    const m = /^[-+]?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/i.exec(d.slice(i, i + 40));
    if (!m) throw new Error(`bad number at ${i}: ${d.slice(i, i + 12)}`);
    i += m[0].length;
    return Number(m[0]);
  };
  const flag = () => { skip(); const c = d[i++]; if (c !== '0' && c !== '1') throw new Error(`bad arc flag ${c}`); return Number(c); };
  const atCommand = () => { skip(); return i < d.length && /[a-zA-Z]/.test(d[i]); };
  for (skip(); i < d.length; skip()) {
    if (atCommand()) cmd = d[i++];
    const lc = cmd.toLowerCase();
    const rel = cmd !== cmd.toUpperCase();
    if (lc === 'z') { out.push('z'); x = sx; y = sy; rx = rsx; ry = rsy; if (cmd) cmd = ''; continue; }
    const n = ARGS[lc];
    if (n === undefined) throw new Error(`path command ${cmd}`);
    const a = [];
    for (let k = 0; k < n; k++) a.push(lc === 'a' && (k === 3 || k === 4) ? flag() : num());
    const bx = rel ? x : 0; const by = rel ? y : 0; // base of this command's coordinates
    const abs = (px, py) => [bx + px, by + py];
    const o = (ax, ay) => [R(ax - rx), R(ay - ry)]; // offset from the rounded current point
    let parts;
    let ex; let ey;
    if (lc === 'h') { ex = bx + a[0]; ey = y; if (!rel) ex = a[0]; parts = ['h', R(ex - rx)]; }
    else if (lc === 'v') { ex = x; ey = rel ? y + a[0] : a[0]; parts = ['v', R(ey - ry)]; }
    else if (lc === 'a') {
      [ex, ey] = abs(a[5], a[6]);
      parts = ['a', R(a[0]), R(a[1]), R(a[2]), a[3], a[4], ...o(ex, ey)];
    } else {
      const pts = [];
      for (let k = 0; k < n; k += 2) pts.push(abs(a[k], a[k + 1]));
      [ex, ey] = pts[pts.length - 1];
      parts = [lc, ...pts.flatMap(([px, py]) => o(px, py))];
    }
    out.push(parts);
    const dx = parts[0] === 'h' ? parts[1] : parts[0] === 'v' ? 0 : parts[parts.length - 2];
    const dy = parts[0] === 'v' ? parts[1] : parts[0] === 'h' ? 0 : parts[parts.length - 1];
    rx += dx; ry += dy; x = ex; y = ey;
    if (lc === 'm') { sx = x; sy = y; rsx = rx; rsy = ry; cmd = rel ? 'l' : 'L'; }
  }
  // the first move is absolute either way (offset from 0,0)
  return out.map((p) => (p === 'z' ? 'z' : p[0] + p.slice(1).join(' ').replace(/ -/g, '-'))).join('');
}

// run as a script (tests import roundPath only)
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const src = process.argv[2];
  if (!src) {
    console.error('usage: node tools/build-icons.mjs <path to @iconify-json/game-icons icons.json>');
    process.exit(1);
  }
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const set = JSON.parse(readFileSync(src, 'utf8'));

  const names = [...new Set(Object.values(ICON_MAP).map(([n]) => n))].sort();
  const out = {};
  for (const name of names) {
    const icon = set.icons[name];
    if (!icon) throw new Error(`no icon "${name}" in ${src}`);
    const m = /\sd="([^"]+)"/.exec(icon.body);
    if (!m || (icon.body.match(/<path/g) || []).length !== 1) throw new Error(`icon "${name}" is not one path`);
    out[name] = roundPath(m[1]);
  }
  const lines = names.map((n) => `  '${n}': '${out[n]}',`);
  const file = `// Generated by tools/build-icons.mjs from @iconify-json/game-icons (game-icons.net, CC BY 3.0,
  // vendor/game-icons/LICENSE.md). Do not edit: change src/ui/icon-map.js and run the tool again.
  // Each value is one SVG path in a 512 x 512 box.

  export const ICON_PATHS = {
  ${lines.join('\n')}
  };
  `;
  writeFileSync(join(root, 'src/ui/icon-paths.js'), file);
  console.log(`${names.length} icons, ${(file.length / 1024).toFixed(0)} KB`);
}
